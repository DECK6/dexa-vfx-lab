#!/usr/bin/env node
/**
 * Generates src/fx/manifest.gen.ts from effects/<cat>/<ID>_<slug>.{meta,effect} pairs.
 * Bundler-agnostic (works in Vite AND Remotion's webpack) — import.meta.glob is Vite-only.
 * Run before dev/build/typecheck/studio. Deterministic output (sorted by ID).
 */
import { readdirSync, writeFileSync, existsSync, statSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const EFFECTS = join(ROOT, 'effects');
const OUT = join(ROOT, 'src/fx/manifest.gen.ts');

const entries = [];
if (existsSync(EFFECTS)) {
  for (const cat of readdirSync(EFFECTS).sort()) {
    const catDir = join(EFFECTS, cat);
    if (!statSync(catDir).isDirectory()) continue;
    for (const file of readdirSync(catDir).sort()) {
      const m = file.match(/^([A-Z]\d{2})_([a-z0-9-]+)\.meta\.ts$/);
      if (!m) continue;
      const base = `${m[1]}_${m[2]}`;
      const ext = existsSync(join(catDir, `${base}.effect.tsx`))
        ? '.effect.tsx'
        : existsSync(join(catDir, `${base}.effect.ts`))
          ? '.effect.ts'
          : null;
      if (!ext) continue; // pair mismatch is reported by lint-registry
      const metaSource = readFileSync(join(catDir, file), 'utf8');
      const assignment = metaSource.indexOf('const meta =');
      const satisfies = metaSource.lastIndexOf('satisfies FxMeta');
      if (assignment < 0 || satisfies < 0) {
        throw new Error(`Cannot extract meta literal from ${cat}/${file}`);
      }
      const equals = metaSource.indexOf('=', assignment);
      const metaLiteral = metaSource.slice(equals + 1, satisfies).trim().replace(/,\s*$/, '');
      entries.push({ id: m[1], cat, base, ext, metaLiteral });
    }
  }
}
entries.sort((a, b) => a.id.localeCompare(b.id));

const lines = [
  '// AUTO-GENERATED by scripts/gen-manifest.mjs — do not edit, do not commit conflicts by hand.',
  "import type { FxKernel, FxMeta } from './types';",
  '',
  'export interface ManifestEntry {',
  '  meta: FxMeta;',
  '  /** repo-relative path of the effect file (key for source loading) */',
  '  effectPath: string;',
  '  load: () => Promise<{ default: FxKernel }>;',
  '}',
  '',
  'export const manifest: ManifestEntry[] = [',
  ...entries.map(
    (e) =>
      `  { meta: ${e.metaLiteral}, effectPath: 'effects/${e.cat}/${e.base}${e.ext}', load: () => import('../../effects/${e.cat}/${e.base}.effect') },`,
  ),
  '];',
  '',
];

const next = lines.join('\n');
const prev = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
if (prev !== next) writeFileSync(OUT, next);
console.log(`gen-manifest — ${entries.length} effects`);
