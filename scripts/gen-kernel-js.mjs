#!/usr/bin/env node
/**
 * Transpile framework-neutral effect kernels for build-step-free HyperFrames HTML.
 * Output is an eager repo-relative-path -> CommonJS source map.
 */
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { transform } from 'esbuild';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const EFFECTS = join(ROOT, 'effects');
const OUT = join(ROOT, 'src/export/kernel-js.gen.ts');

const effectFiles = [];
if (existsSync(EFFECTS)) {
  for (const category of readdirSync(EFFECTS).sort()) {
    const categoryDir = join(EFFECTS, category);
    if (!statSync(categoryDir).isDirectory()) continue;
    for (const file of readdirSync(categoryDir).sort()) {
      if (/\.effect\.tsx?$/.test(file)) effectFiles.push(join(categoryDir, file));
    }
  }
}

const entries = [];
for (const file of effectFiles) {
  const result = await transform(readFileSync(file, 'utf8'), {
    loader: 'tsx',
    jsxFactory: 'h',
    jsxFragment: 'Frag',
    format: 'cjs',
    target: 'es2020',
    sourcefile: relative(ROOT, file).split(sep).join('/'),
    legalComments: 'none',
  });
  entries.push([relative(ROOT, file).split(sep).join('/'), result.code]);
}

const lines = [
  '// AUTO-GENERATED by scripts/gen-kernel-js.mjs — do not edit by hand.',
  'export const kernelJsByEffectPath: Readonly<Record<string, string>> = {',
  ...entries.map(([effectPath, source]) => `  ${JSON.stringify(effectPath)}: ${JSON.stringify(source)},`),
  '};',
  '',
];
const next = lines.join('\n');
const previous = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
if (next !== previous) writeFileSync(OUT, next);
console.log(`gen-kernel-js — ${entries.length} effects`);
