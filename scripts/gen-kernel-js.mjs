#!/usr/bin/env node
/**
 * Transpile framework-neutral effect kernels for build-step-free HyperFrames HTML.
 * Output is code-split: one module per effect (src/export/kernel-js/<ID>.ts) plus a
 * lazy loader map (kernel-js.gen.ts) so kernel JS never lands in the entry chunk.
 */
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, relative, resolve, sep, basename } from 'node:path';
import { fileURLToPath } from 'node:url';
import { transform } from 'esbuild';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const EFFECTS = join(ROOT, 'effects');
const OUT = join(ROOT, 'src/export/kernel-js.gen.ts');
const OUT_DIR = join(ROOT, 'src/export/kernel-js');

const effectFiles = [];
if (existsSync(EFFECTS)) {
  for (const category of readdirSync(EFFECTS).sort()) {
    const categoryDir = join(EFFECTS, category);
    if (!statSync(categoryDir).isDirectory()) continue;
    for (const file of readdirSync(categoryDir).sort()) {
      if (/\.effect\.tsx?$/.test(file)) effectFiles.push(join(categoryDir, file));
    }
  }
}

const entries = [];
for (const file of effectFiles) {
  const result = await transform(readFileSync(file, 'utf8'), {
    loader: 'tsx',
    jsxFactory: 'h',
    jsxFragment: 'Frag',
    format: 'cjs',
    target: 'es2020',
    sourcefile: relative(ROOT, file).split(sep).join('/'),
    legalComments: 'none',
  });
  const id = basename(file).split('_')[0];
  entries.push({ id, effectPath: relative(ROOT, file).split(sep).join('/'), source: result.code });
}

// Per-effect modules. The generated loader map is authoritative; unreferenced old
// files are harmless and intentionally preserved so generation is non-destructive.
mkdirSync(OUT_DIR, { recursive: true });
for (const e of entries) {
  writeFileSync(
    join(OUT_DIR, `${e.id}.ts`),
    `// AUTO-GENERATED — kernel JS for ${e.effectPath}\nexport default ${JSON.stringify(e.source)};\n`,
  );
}

const lines = [
  '// AUTO-GENERATED by scripts/gen-kernel-js.mjs — do not edit by hand.',
  '/** Lazy per-effect kernel JS loaders, keyed by repo-relative effect path. */',
  'export const kernelJsLoaders: Readonly<Record<string, () => Promise<string>>> = {',
  ...entries.map(
    (e) => `  ${JSON.stringify(e.effectPath)}: () => import('./kernel-js/${e.id}').then((m) => m.default),`,
  ),
  '};',
  '',
];
const next = lines.join('\n');
const previous = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
if (next !== previous) writeFileSync(OUT, next);
console.log(`gen-kernel-js — ${entries.length} effects (code-split)`);
